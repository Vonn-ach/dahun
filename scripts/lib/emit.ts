import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import type { Bundle, Channel, LanguageSummary } from '../../src/content/types';
import { summarize } from './bundle';

const BUNDLE_FILE = /^[a-z]{3}\.bundle\.json$/;

export interface EmitResult {
  files: { path: string; bytes: number }[];
}

/** The TypeScript module the app imports: the language list plus one lazy loader per language. */
export function indexSource(summaries: readonly LanguageSummary[], channel: Channel): string {
  const list = summaries.map((s) => `  ${JSON.stringify(s)},`).join('\n');
  const loaders = summaries
    .map(
      (s) =>
        `  ${JSON.stringify(s.code)}: () =>\n    import('./${s.code}.bundle.json').then((m) => m.default as unknown as Bundle),`,
    )
    .join('\n');
  return `// Generated by scripts/build-content.ts. Do not edit: it is rebuilt by
// npm run dev / build / build:draft. Each language is its own chunk.
import type { Bundle, Channel, LanguageSummary } from '../content/types';

export const channel: Channel = ${JSON.stringify(channel)};

export const languages: readonly LanguageSummary[] = [
${list}
];

export const loaders: Readonly<Record<string, () => Promise<Bundle>>> = {
${loaders}
};
`;
}

/**
 * Writes <code>.bundle.json (minified) for each pack, index.ts and meta.json
 * into outDir, and removes bundles of packs that no longer exist. It only
 * touches files it owns inside outDir.
 */
export function emitBundles(
  bundles: readonly Bundle[],
  channel: Channel,
  outDir: string,
  /** The content folder the bundles were built from, relative to the repo ("content" normally). */
  contentDir = 'content',
): EmitResult {
  mkdirSync(outDir, { recursive: true });
  const sorted = [...bundles].sort((a, b) => a.code.localeCompare(b.code));
  const keep = new Set(sorted.map((b) => `${b.code}.bundle.json`));
  for (const file of readdirSync(outDir)) {
    if (BUNDLE_FILE.test(file) && !keep.has(file)) rmSync(path.join(outDir, file));
  }

  const files: EmitResult['files'] = [];
  const write = (name: string, text: string) => {
    const full = path.join(outDir, name);
    writeFileSync(full, text);
    files.push({ path: full, bytes: Buffer.byteLength(text) });
  };
  for (const bundle of sorted) write(`${bundle.code}.bundle.json`, JSON.stringify(bundle));
  write('index.ts', indexSource(sorted.map(summarize), channel));
  // Read by vite.config.ts: noindex for builds that aren't release builds (D007),
  // and the build guard, which refuses bundles that didn't come from content/.
  write('meta.json', `${JSON.stringify({ channel, contentDir })}\n`);
  return { files };
}
